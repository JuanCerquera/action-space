"""Bundle our swarm_ops policies into ONE drag-and-drop file: dist/policy.py.

    python scripts/build_policy.py

The output embeds the source of defense/{blocker,team,attack_script}.py and
deploy/swarm_ops/{pose_sources,tag_localizer,team_defense,move_test}.py and loads each as its
own module at import, so nothing collides and no other files are needed. Install: drop
policy.py into the judges' swarm_ops/policies/ and add one line at the END of
policies/__init__.py:  from .policy import *   (it registers "defense" and "movetest").
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = [  # (module name inside the bundle, source file); dependencies first
    ("defense", None),
    ("defense.blocker", "defense/blocker.py"),
    ("defense.team", "defense/team.py"),
    ("defense.attack_script", "defense/attack_script.py"),
    ("pose_sources", "deploy/swarm_ops/pose_sources.py"),
    ("tag_localizer", "deploy/swarm_ops/tag_localizer.py"),
    ("team_defense", "deploy/swarm_ops/team_defense.py"),
    ("move_test", "deploy/swarm_ops/move_test.py"),
]
POLICY_MODULES = {"team_defense", "move_test"}  # these import `.base` from the judges' policies package

HEADER = '''"""Action Space defense policies for the judges' swarm_ops runner - ONE self-contained file.

Install: copy this file into drone_deployment_infra/swarm_ops/policies/ and add one line at the
END of policies/__init__.py:

    from .policy import *

That registers two policies in POLICIES:
  defense   our 3-drone team defense (block / keeper / ram), e.g.
            DEFENSE_POSE_SOURCE=tags python swarm_policies.py --run defense:1,2,3 --run formation:4,5 --fly
  movetest  take off, 1 m forward, 30 cm to every side, land (all drones at once), e.g.
            python swarm_policies.py --run movetest:1,2,3 --fly --duration 40
Env switches (defense): DEFENSE_POSE_SOURCE=judges|sim|tags, DEFENSE_SIM_ATTACKERS=1,
DEFENSE_ATTACK_MODE=1, DEFENSE_FACE=tag|attacker, DEFENSE_TAG_BACKEND=positional|formation,
DEFENSE_IGNORE_TAGS=1,2,4,...  Needs numpy (+ cv2, av, pupil_apriltags, pyyaml for tags).

GENERATED by scripts/build_policy.py from the action-space repo - edit the sources, not this file.
"""
import sys as _sys
import types as _types

_SOURCES = __SOURCES__
_POLICY_MODULES = __POLICY_MODULES__


def _load():
    pkg = __package__ or ""
    for name, src in _SOURCES:
        if name in _sys.modules and getattr(_sys.modules[name], "__action_space_bundle__", False):
            continue
        if name in _POLICY_MODULES and pkg:
            full = f"{pkg}._as_{name}"  # inside the judges' package: `from .base import Policy` resolves
            mod = _types.ModuleType(full)
            mod.__package__ = pkg
        else:
            full = name
            mod = _types.ModuleType(full)
            mod.__package__ = name if src is None else name.rpartition(".")[0]
            if src is None:
                mod.__path__ = []  # namespace for defense.*
        mod.__file__ = __file__  # tag_localizer finds swarm_formation.py / core/ relative to this file
        mod.__action_space_bundle__ = True
        _sys.modules[full] = mod
        if full != name:
            _sys.modules[name] = mod
        if src is not None:
            exec(compile(src, f"<policy.py:{name}>", "exec"), mod.__dict__)
        if "." in name and src is not None:
            setattr(_sys.modules[name.rpartition(".")[0]], name.rpartition(".")[2], mod)
    return _sys.modules["team_defense"], _sys.modules["move_test"]


_td, _mt = _load()
TeamDefensePolicy = _td.TeamDefensePolicy
MoveTestPolicy = _mt.MoveTestPolicy
NEW_POLICIES = {"defense": TeamDefensePolicy, "movetest": MoveTestPolicy}

try:  # registered when imported from the end of policies/__init__.py
    from . import POLICIES as _POLICIES
    _POLICIES.update(NEW_POLICIES)
except ImportError:
    pass

__all__ = ["TeamDefensePolicy", "MoveTestPolicy", "NEW_POLICIES"]
'''


def main():
    sources = [(name, None if path is None else (ROOT / path).read_text(encoding="utf-8")) for name, path in MODULES]
    out = HEADER.replace("__SOURCES__", repr(sources)).replace(
        "__POLICY_MODULES__", repr(sorted(POLICY_MODULES)))
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    (dist / "policy.py").write_text(out, encoding="utf-8")
    print(f"wrote {dist / 'policy.py'} ({len(out) // 1024} KB, {len(sources)} modules)")


if __name__ == "__main__":
    main()
