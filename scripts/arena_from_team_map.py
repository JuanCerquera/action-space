"""Build config/arena_team.json (our arena format) from the team's MEASURED tag map (config/team_map.yaml).

team_map.yaml (cal_and_map bundle adjustment) holds every tag's pose in tag 10's frame (x right, y up,
z out of the face). The room frame here is the one MapFrames in tello/defense_policy.py uses:
x = out of the tag-10 wall, y = tag 10's right, z = up from the floor (tag 10 height from the floor tags).
Room walls are estimated from the tag extents (tags sit on or near walls); the goal is tag 10's face.

    python scripts/arena_from_team_map.py            # writes config/arena_team.json
"""

import json
import os

import numpy as np
import yaml

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SIZES = {10: 0.5715}  # everything else is 132.08 mm (tags.yaml)


def main():
    with open(os.path.join(REPO, "config", "team_map.yaml")) as f:
        m = yaml.safe_load(f)
    tags = {int(k): (np.asarray(v["R"], float), np.asarray(v["t"], float)) for k, v in m["tags"].items()}
    floor = [t[1] for R, t in tags.values() if R[1, 2] > 0.9]
    h10 = -float(np.median(floor)) if floor else 1.22

    def room(v, point=True):
        return np.array([v[2], v[0], v[1] + (h10 if point else 0.0)])

    out_tags = []
    for k, (R, t) in sorted(tags.items()):
        out_tags.append({"id": k, "size_m": SIZES.get(k, 0.13208), "center": room(t).round(3).tolist(),
                         "normal": room(R[:, 2], False).round(3).tolist(), "up": room(R[:, 1], False).round(3).tolist()})
    c = np.array([t["center"] for t in out_tags])
    lo = c.min(axis=0) - 0.5
    hi = c.max(axis=0) + 0.6
    lo[0], lo[2], hi[2] = 0.0, 0.0, 3.0  # the tag-10 wall, the floor, the ceiling
    half = SIZES[10] / 2 + 0.1
    arena = {
        "_notes": [
            "Generated by scripts/arena_from_team_map.py from the team's measured map (config/team_map.yaml).",
            "Frame: origin on the floor below tag 10, +x out of the tag-10 wall, +y = tag 10's right, +z up.",
            f"Tag 10 is {h10:.2f} m above the floor (from the floor tags). Room walls are ESTIMATED from the tag extents.",
            "Goal = touching tag 10 (the big picture). Defender starts / attacker spawn are placeholders.",
        ],
        "tag_family": "tag36h11",
        "room": {"x": [round(lo[0], 2), round(hi[0], 2)], "y": [round(lo[1], 2), round(hi[1], 2)], "z": [0.0, 3.0]},
        "goal": {"tag_id": 10, "zone": {"x": [0.0, 0.3], "y": [-half, half], "z": [round(h10 - half, 2), round(h10 + half, 2)]}},
        "tags": out_tags,
        "defender_starts": [[1.2, -0.6, 0.0], [1.0, 0.0, 0.0], [1.2, 0.6, 0.0]],
        "attacker_spawn": {"x": [round(hi[0] - 1.6, 2), round(hi[0] - 0.6, 2)], "y": [round(lo[1] + 0.6, 2), round(hi[1] - 0.6, 2)],
                           "z": [0.8, 1.8]},
    }
    path = os.path.join(REPO, "config", "arena_team.json")
    with open(path, "w") as f:
        json.dump(arena, f, indent=2)
    print(f"wrote {path}: room x {arena['room']['x']} y {arena['room']['y']}, tag 10 at {h10:.2f} m, {len(out_tags)} tags")


if __name__ == "__main__":
    main()
